"""Requirements checker and traceability-matrix generator (stdlib only).

Checks docs/se/requirements.json:
  1. every requirement has an ID, a 'shall' statement, a verification method, a need and a design element
  2. wording lint: vague or untestable words are flagged
  3. duplicate requirement text is flagged
  4. every referenced test really exists in tests/ (parsed with ast)
  5. optionally, with --junit FILE, reports each requirement as verified / failing / not run
Writes docs/se/TRACEABILITY.md. Exit code 1 if any check fails.
"""

from __future__ import annotations

import argparse
import ast
import json
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
VAGUE = [
    "fast",
    "quick",
    "safe",
    "secure",
    "user-friendly",
    "efficient",
    "robust",
    "as possible",
    "appropriate",
    "reasonable",
    "adequate",
    "etc",
    "should",
    "may ",
    "easy",
]


def tests_on_disk() -> set[str]:
    found: set[str] = set()
    for f in (ROOT / "tests").glob("test_*.py"):
        rel = f.relative_to(ROOT).as_posix()
        for node in ast.walk(ast.parse(f.read_text(encoding="utf-8"))):
            if isinstance(node, ast.FunctionDef) and node.name.startswith("test_"):
                found.add(f"{rel}::{node.name}")
    return found


def junit_status(path: Path) -> dict[str, str]:
    res: dict[str, str] = {}
    for tc in ET.parse(path).getroot().iter("testcase"):  # noqa: S314 - our own pytest output
        mod = tc.get("classname", "").replace(".", "/") + ".py"
        name = (tc.get("name") or "").split("[")[0]
        key = f"{mod}::{name}"
        bad = any(c.tag in ("failure", "error") for c in tc)
        skipped = any(c.tag == "skipped" for c in tc)
        prev = res.get(key)
        res[key] = "fail" if bad or prev == "fail" else ("skip" if skipped and prev in (None, "skip") else "pass")
    return res


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--junit", type=Path)
    args = ap.parse_args()
    reqs = json.loads((ROOT / "docs/se/requirements.json").read_text(encoding="utf-8"))
    on_disk = tests_on_disk()
    status = junit_status(args.junit) if args.junit else {}
    problems: list[str] = []
    seen: dict[str, str] = {}
    ids = set()
    rows = []
    for r in reqs:
        rid = r["id"]
        if rid in ids:
            problems.append(f"{rid}: duplicate ID")
        ids.add(rid)
        if not re.match(r"^REQ-\d{3}$", rid):
            problems.append(f"{rid}: ID should look like REQ-001")
        text = r["text"]
        if not re.search(r"\bshall\b", text):
            problems.append(f"{rid}: no 'shall'")
        low = text.lower()
        for w in VAGUE:
            if re.search(rf"\b{re.escape(w.strip())}\b", low):
                problems.append(f"{rid}: vague or weak word '{w.strip()}'")
        for k in ("need", "design", "method"):
            if not r.get(k):
                problems.append(f"{rid}: missing {k}")
        is_test_method = r.get("method", "").lower().startswith("test")
        if is_test_method and not r["tests"]:
            problems.append(f"{rid}: method is Test but no test is linked")
        norm = re.sub(r"\W+", " ", low).strip()
        if norm in seen:
            problems.append(f"{rid}: duplicates {seen[norm]}")
        seen[norm] = rid
        missing = [t for t in r["tests"] if t not in on_disk]
        for t in missing:
            problems.append(f"{rid}: test not found: {t}")
        if not is_test_method:
            v = "manual evidence needed"  # Demonstration, Inspection or Analysis: record the evidence by hand
        elif status:
            st = [status.get(t, "not run") for t in r["tests"]]
            v = "FAILING" if "fail" in st else ("verified" if all(s == "pass" for s in st) else "partly run/skipped")
        else:
            v = "not run"
        rows.append((r, v))
    lines = [
        "# Traceability matrix",
        "",
        "Generated by `python scripts/trace_check.py`. Edit `docs/se/requirements.json`, not this file.",
        "",
        "| ID | Requirement | Need | Design element | Tests | Method | Status |",
        "|----|-------------|------|----------------|-------|--------|--------|",
    ]
    for r, v in rows:
        t = "<br>".join(f"`{x}`" for x in r["tests"])
        lines.append(f"| {r['id']} | {r['text']} | {r['need']} | {r['design']} | {t} | {r['method']} | {v} |")
    (ROOT / "docs/se/TRACEABILITY.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    used = {t for r in reqs for t in r["tests"]}
    orphan = sorted(on_disk - used)
    print(
        f"{len(reqs)} requirements, {len(used)} linked tests, {len(on_disk)} tests on disk, {len(orphan)} not linked to any requirement"
    )
    for p in problems:
        print("PROBLEM:", p)
    if status:
        for r, v in rows:
            if v != "verified":
                print(f"STATUS {r['id']}: {v}")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
